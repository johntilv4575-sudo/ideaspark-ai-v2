import { downloadTextFile, fileBase } from "@/lib/downloadFile";

export { downloadTextFile };

export function promptFileBase(projectName) {
  return fileBase(projectName);
}

export function buildPromptFile({ title, role, prompt, projectName, mainFeature, customContext }) {
  const context = [
    projectName ? `**Project:** ${projectName}` : "",
    mainFeature ? `**Focus Area:** ${mainFeature}` : "",
    customContext ? `**Additional Context:**\n${customContext}` : "",
  ].filter(Boolean);

  return [
    `# ${title}`,
    role,
    "",
    ...(context.length ? [context.join("\n"), ""] : []),
    "---",
    "",
    prompt,
    "",
    "---",
    "Generated by Idea Spark — Spiral Beyond",
  ].join("\n");
}

export function buildCombinedPrompts({ architect, builder, projectName, mainFeature, customContext }) {
  const context = [
    projectName ? `**Project:** ${projectName}` : "",
    mainFeature ? `**Focus Area:** ${mainFeature}` : "",
    customContext ? `**Additional Context:**\n${customContext}` : "",
  ].filter(Boolean);

  return [
    "# Architect & Builder Prompts",
    "Two separate prompts, used in two separate chats.",
    "",
    ...(context.length ? [context.join("\n"), ""] : []),
    "---",
    "",
    "## 1. Architect Prompt",
    "_Defines WHAT you are building and WHY. Run this first, in a fresh chat._",
    "",
    architect,
    "",
    "---",
    "",
    "## 2. Builder Prompt",
    "_Implements the plan in code. Run this in a separate chat, after the Architect has produced the plan._",
    "",
    builder,
    "",
    "---",
    "",
    "Rhythm: Architect → Build Brief → Builder → Code → Review → Integrate",
    "The Architect is the source of truth. The Builder implements only what the Architect has defined.",
    "",
    "Generated by Idea Spark — Spiral Beyond",
  ].join("\n");
}