import React, { useState } from "react";
import { Button } from "@/components/ui/button";
import {
  DropdownMenu,
  DropdownMenuContent,
  DropdownMenuItem,
  DropdownMenuTrigger,
} from "@/components/ui/dropdown-menu";
import {
  Download,
  FileText,
  FileCode2,
  Code2,
  ClipboardCopy,
  Loader2,
  ChevronDown,
} from "lucide-react";
import { toast } from "sonner";
import { jsPDF } from "jspdf";
import { base44 } from "@/api/base44Client";
import { canPerformAction, incrementUsage } from "@/components/utils/pricing";

const sanitize = (name) => (name || "concept").replace(/[^a-z0-9]/gi, "_");

function buildBlueprintText(concept, industry) {
  const line = "═══════════════════════════════════════════════════════════";
  return [
    line,
    "              DEVELOPMENT BLUEPRINT",
    line,
    "",
    `Concept: ${concept.concept_name}`,
    concept.one_liner ? `Pitch: ${concept.one_liner}` : "",
    concept.target_user ? `Target User: ${concept.target_user}` : "",
    `Industry: ${industry}`,
    `Generated: ${new Date().toLocaleDateString()}`,
    "",
    line, "CORE SOLUTION", line, "",
    concept.core_solution || "N/A",
    "",
    line, "TARGET AUDIENCE & PROBLEM", line, "",
    concept.target_pain_points?.map((p, i) => `${i + 1}. ${p}`).join("\n") || "N/A",
    "",
    concept.proposed_solution_sources?.length
      ? [line, "RESEARCH-DERIVED SOLUTION SOURCES", line, "",
         concept.proposed_solution_sources.map((s, i) => `${i + 1}. ${s}`).join("\n"), ""].join("\n")
      : "",
    line, "KEY FEATURES", line, "",
    concept.key_features?.map((f, i) => `${i + 1}. ${f}`).join("\n") || "N/A",
    "",
    concept.mvp_scope
      ? [line, "MVP SCOPE", line, "",
         "IN SCOPE:", concept.mvp_scope.in_scope?.map((i2, i) => `${i + 1}. ${i2}`).join("\n") || "N/A",
         "", "OUT OF SCOPE:", concept.mvp_scope.out_of_scope?.map((i2, i) => `${i + 1}. ${i2}`).join("\n") || "N/A", ""].join("\n")
      : "",
    concept.differentiation ? [line, "DIFFERENTIATION", line, "", concept.differentiation, ""].join("\n") : "",
    line, "COMPETITIVE ADVANTAGE", line, "",
    concept.competitive_advantage || "N/A",
    "",
    concept.risks_assumptions?.length
      ? [line, "RISKS & ASSUMPTIONS", line, "", concept.risks_assumptions.map((r, i) => `${i + 1}. ${r}`).join("\n"), ""].join("\n")
      : "",
    concept.validation_plan?.length
      ? [line, "VALIDATION PLAN", line, "", concept.validation_plan.map((t, i) => `${i + 1}. ${t}`).join("\n"), ""].join("\n")
      : "",
    line,
    `DEVELOPMENT COMPLEXITY: ${(concept.development_complexity || "medium").toUpperCase()}`,
    `MARKET POTENTIAL: ${(concept.market_potential || "moderate").toUpperCase()}`,
    line,
    "",
    "Generated by Idea Spark AI - Spiral Beyond",
  ].filter((l) => l !== "").join("\n");
}

function buildMarkdown(concept, industry) {
  const list = (items, ordered = false) =>
    (items || []).map((t, i) => `${ordered ? `${i + 1}.` : "-"} ${t}`).join("\n");

  return [
    `# ${concept.concept_name}`,
    concept.one_liner ? `> ${concept.one_liner}` : "",
    `**Industry:** ${industry}`,
    concept.target_user ? `**Target User:** ${concept.target_user}` : "",
    "",
    "## Core Solution", concept.core_solution || "N/A", "",
    "## Target Audience & Problem", list(concept.target_pain_points, true) || "N/A", "",
    concept.proposed_solution_sources?.length
      ? ["## Research-Derived Solution Sources", list(concept.proposed_solution_sources, true), ""].join("\n")
      : "",
    "## Key Features", list(concept.key_features, true) || "N/A", "",
    concept.mvp_scope
      ? ["## MVP Scope", "**In scope**", list(concept.mvp_scope.in_scope), "", "**Out of scope**", list(concept.mvp_scope.out_of_scope), ""].join("\n")
      : "",
    concept.differentiation ? ["## Differentiation", concept.differentiation, ""].join("\n") : "",
    "## Competitive Advantage", concept.competitive_advantage || "N/A", "",
    concept.risks_assumptions?.length ? ["## Risks & Assumptions", list(concept.risks_assumptions), ""].join("\n") : "",
    concept.validation_plan?.length ? ["## Validation Plan", list(concept.validation_plan, true), ""].join("\n") : "",
    "---",
    `**Development Complexity:** ${concept.development_complexity || "medium"}  `,
    `**Market Potential:** ${concept.market_potential || "moderate"}`,
    "",
    "*Generated by Idea Spark AI — Spiral Beyond*",
  ].filter((l) => l !== "").join("\n");
}

function downloadBlob(content, mime, filename) {
  const blob = new Blob([content], { type: mime });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

export default function BlueprintExportMenu({ concept, industry, onBlocked }) {
  const [isExporting, setIsExporting] = useState(false);
  const base = sanitize(concept.concept_name);

  const gate = async () => {
    const { allowed, reason } = await canPerformAction("export");
    if (!allowed) {
      toast.error(reason);
      if (onBlocked) onBlocked();
      return false;
    }
    return true;
  };

  const runExport = async (format, fn) => {
    if (!(await gate())) return;
    setIsExporting(true);
    try {
      await incrementUsage("export");
      fn();
      base44.analytics.track({ eventName: "data_exported", properties: { format } });
    } catch (error) {
      console.error("Export error:", error);
      toast.error("Failed to export. Please try again.");
    } finally {
      setIsExporting(false);
    }
  };

  const handlePdf = () =>
    runExport("pdf", () => {
      const doc = new jsPDF({ unit: "mm", format: "a4" });
      const pageH = 297;
      const marginB = 20;
      let y = 20;

      doc.setFontSize(18);
      doc.setFont("helvetica", "bold");
      doc.text(concept.concept_name || "Concept", 15, y);
      y += 10;
      doc.setFontSize(10);
      doc.setFont("helvetica", "normal");
      doc.setTextColor(100, 116, 139);
      doc.text(`Industry: ${industry}  |  Generated: ${new Date().toLocaleDateString()}`, 15, y);
      y += 10;
      doc.setTextColor(40, 40, 40);

      const lines = doc.splitTextToSize(buildBlueprintText(concept, industry), 180);
      lines.forEach((line) => {
        if (y + 5 > pageH - marginB) {
          doc.addPage();
          y = 20;
        }
        doc.text(line, 15, y);
        y += 5;
      });

      doc.save(`${base}_Blueprint.pdf`);
      toast.success("PDF exported successfully!");
    });

  const handleMarkdown = () =>
    runExport("markdown", () => {
      downloadBlob(buildMarkdown(concept, industry), "text/markdown;charset=utf-8", `${base}_Blueprint.md`);
      toast.success("Markdown exported successfully!");
    });

  const handleJson = () =>
    runExport("json", () => {
      const data = {
        concept,
        industry,
        blueprint: buildBlueprintText(concept, industry),
        exported_at: new Date().toISOString(),
      };
      downloadBlob(JSON.stringify(data, null, 2), "application/json", `${base}_Blueprint.json`);
      toast.success("JSON exported successfully!");
    });

  const handleText = () =>
    runExport("text", () => {
      downloadBlob(buildBlueprintText(concept, industry), "text/plain;charset=utf-8", `${base}_Blueprint.txt`);
      toast.success("Text file exported successfully!");
    });

  const handleCopy = async () => {
    if (!(await gate())) return;
    await navigator.clipboard.writeText(buildBlueprintText(concept, industry));
    toast.success("Blueprint copied to clipboard!");
  };

  return (
    <DropdownMenu>
      <DropdownMenuTrigger asChild>
        <Button
          type="button"
          disabled={isExporting}
          className="w-full text-lg py-6 bg-blue-600 hover:bg-blue-700 text-white disabled:opacity-50"
        >
          {isExporting ? (
            <>
              <Loader2 className="w-5 h-5 mr-3 animate-spin" />
              Generating…
            </>
          ) : (
            <>
              <Download className="w-5 h-5 mr-3" />
              Export Blueprint
              <ChevronDown className="w-4 h-4 ml-2" />
            </>
          )}
        </Button>
      </DropdownMenuTrigger>
      <DropdownMenuContent align="center" className="w-64 bg-white border-slate-200">
        <DropdownMenuItem onClick={handlePdf} className="cursor-pointer gap-2 text-gray-700">
          <FileText className="w-4 h-4 text-red-500" />
          Download as PDF
        </DropdownMenuItem>
        <DropdownMenuItem onClick={handleMarkdown} className="cursor-pointer gap-2 text-gray-700">
          <FileCode2 className="w-4 h-4 text-blue-500" />
          Download as Markdown (.md)
        </DropdownMenuItem>
        <DropdownMenuItem onClick={handleJson} className="cursor-pointer gap-2 text-gray-700">
          <Code2 className="w-4 h-4 text-green-600" />
          Download as JSON
        </DropdownMenuItem>
        <DropdownMenuItem onClick={handleText} className="cursor-pointer gap-2 text-gray-700">
          <FileText className="w-4 h-4 text-slate-500" />
          Download as Text (.txt)
        </DropdownMenuItem>
        <DropdownMenuItem onClick={handleCopy} className="cursor-pointer gap-2 text-gray-700">
          <ClipboardCopy className="w-4 h-4 text-purple-500" />
          Copy to Clipboard
        </DropdownMenuItem>
      </DropdownMenuContent>
    </DropdownMenu>
  );
}